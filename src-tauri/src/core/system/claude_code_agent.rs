use std::process::Stdio;

use tauri::{AppHandle, Emitter, Runtime, State};
use tokio::io::{AsyncBufReadExt, BufReader};
use tokio::process::Command as TokioCommand;
use tokio::sync::oneshot;

use crate::core::state::AppState;

/// Payload emitted to the frontend for each JSONL line produced by `claude`.
/// The `session_id` lets the frontend route events to the correct agent session
/// when multiple turns are in flight (only one runs at a time today).
#[derive(Debug, Clone, serde::Serialize)]
struct ClaudeAgentEvent {
    event: serde_json::Value,
    session_id: String,
}

/// Spawn a Claude Code agent turn and stream the resulting JSONL events back
/// to the frontend via the `claude://agent-event` Tauri event channel.
///
/// Uses `claude --output-format stream-json -p <prompt>`.  For multi-turn
/// conversations, pass the `claude_session_id` returned by the previous call;
/// the CLI will resume via `claude --resume <id> -p <prompt>`.
///
/// Returns the Claude session ID (stable across turns within a conversation).
#[tauri::command]
pub async fn claude_run_turn<R: Runtime>(
    app: AppHandle<R>,
    state: State<'_, AppState>,
    // Opaque ID generated by the frontend to disambiguate concurrent calls.
    session_id: String,
    prompt: String,
    // Pass null for the first turn, then pass the returned value to resume.
    claude_session_id: Option<String>,
    // Directory the agent should treat as the project root.  Defaults to $HOME.
    working_dir: Option<String>,
    // Custom path to the `claude` binary (None → search PATH).
    binary_path: Option<String>,
) -> Result<String, String> {
    let mut args: Vec<String> = vec![
        "--output-format".into(),
        "stream-json".into(),
        "--verbose".into(),
    ];

    // Resume an existing Claude Code session if one was provided.
    let current_claude_session_id = claude_session_id.clone().unwrap_or_default();
    if !current_claude_session_id.trim().is_empty() {
        args.push("--resume".into());
        args.push(current_claude_session_id.clone());
    }

    // Prompt is passed via -p so stdin stays closed.
    args.push("-p".into());
    args.push(prompt.clone());

    // Set up a cancellation channel so `claude_stop_turn` can abort the process.
    let (cancel_tx, cancel_rx) = oneshot::channel::<()>();
    {
        let mut guard = state.claude_cancel.lock().await;
        *guard = Some(cancel_tx);
    }

    let binary = binary_path
        .as_deref()
        .filter(|s| !s.trim().is_empty())
        .unwrap_or("claude");

    let mut cmd = TokioCommand::new(binary);
    cmd.args(&args)
        .stdin(Stdio::null())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped());

    // Resolve and apply the working directory.
    if let Some(ref dir) = working_dir {
        let trimmed = dir.trim();
        if !trimmed.is_empty() {
            let expanded = if trimmed == "~" || trimmed.starts_with("~/") {
                if let Some(home) = std::env::var_os("HOME") {
                    let rest = trimmed.trim_start_matches('~');
                    format!("{}{}", home.to_string_lossy(), rest)
                } else {
                    trimmed.to_string()
                }
            } else {
                trimmed.to_string()
            };
            cmd.current_dir(expanded);
        }
    }

    let mut child = cmd.spawn().map_err(|e| {
        format!(
            "Failed to spawn {binary}: {e}. Is the Claude Code CLI installed and on PATH?"
        )
    })?;

    let stdout = child
        .stdout
        .take()
        .ok_or("claude process produced no stdout")?;

    let reader = BufReader::new(stdout);
    let mut lines = reader.lines();
    let mut resolved_claude_session_id = current_claude_session_id.clone();

    // Emit each JSONL line as a Tauri event, or bail early if cancelled.
    let read_result: Result<String, String> = tokio::select! {
        biased;

        // Cancellation path: kill the process and emit a synthetic event.
        _ = cancel_rx => {
            child.kill().await.ok();
            let _ = app.emit(
                "claude://agent-event",
                &ClaudeAgentEvent {
                    event: serde_json::json!({
                        "type": "result",
                        "subtype": "cancelled",
                        "is_error": false,
                    }),
                    session_id: session_id.clone(),
                },
            );
            Ok(resolved_claude_session_id.clone())
        }

        // Normal path: drain stdout until EOF.
        result = async {
            loop {
                match lines.next_line().await {
                    Ok(Some(line)) => {
                        if line.is_empty() {
                            continue;
                        }
                        match serde_json::from_str::<serde_json::Value>(&line) {
                            Ok(event) => {
                                // Capture the Claude session_id from the system init event.
                                if event["type"].as_str() == Some("system") {
                                    if let Some(sid) = event["session_id"].as_str() {
                                        resolved_claude_session_id = sid.to_string();
                                    }
                                }
                                let _ = app.emit(
                                    "claude://agent-event",
                                    &ClaudeAgentEvent {
                                        event,
                                        session_id: session_id.clone(),
                                    },
                                );
                            }
                            Err(e) => {
                                // Forward malformed lines as error events so the
                                // frontend can surface them rather than silently drop them.
                                let _ = app.emit(
                                    "claude://agent-event",
                                    &ClaudeAgentEvent {
                                        event: serde_json::json!({
                                            "type": "error",
                                            "message": format!("Parse error: {e} — raw: {line}"),
                                        }),
                                        session_id: session_id.clone(),
                                    },
                                );
                            }
                        }
                    }
                    Ok(None) => break, // EOF — Claude finished this turn.
                    Err(e) => return Err(e.to_string()),
                }
            }
            Ok::<(), String>(())
        } => {
            result?;
            Ok(resolved_claude_session_id.clone())
        }
    };

    // Best-effort wait so we don't leave zombie processes around.
    child.wait().await.ok();

    // Release the cancel sender now that the process is done.
    {
        let mut guard = state.claude_cancel.lock().await;
        *guard = None;
    }

    read_result
}

/// Signal the currently-running `claude_run_turn` to terminate early.
#[tauri::command]
pub async fn claude_stop_turn(state: State<'_, AppState>) -> Result<(), String> {
    let mut guard = state.claude_cancel.lock().await;
    if let Some(tx) = guard.take() {
        // Ignore send errors — the receiver may already be gone if the turn
        // finished naturally between the UI click and this handler running.
        tx.send(()).ok();
    }
    Ok(())
}
